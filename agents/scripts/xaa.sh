#!/usr/bin/env bash
#
# xaa agent script for the repo-local bash-script Harbor agent
# (bash_script_agent.agent:BashScriptAgent).
#
# Contract (see agents/scripts/README.md):
#   * The scenario's `model` value points at this file, relative to the
#     repository root.
#   * Runs inside the task container as the agent user, in /workspace
#     (the cloned sandbox repository), with `git` and authenticated `gh`
#     ready.
#   * The task prompt is in the INSTRUCTION environment variable.
#   * Exit 0 only when xaa considers the task done; any non-zero exit fails
#     the trial (the separate verifier still decides the final reward).

set -euo pipefail

# Defense in depth: the image already sets X_AEON_AGENTS_CONFIG via
# Dockerfile ENV (pointing at /etc/x_aeon_agents.rb), but re-export it
# here so manual `harbor run` invocations or agent setups that bypass
# the image default still keep the sessions/... tree out of /workspace
# (which task.toml uploads as an artifact into the separate verifier).
export X_AEON_AGENTS_CONFIG="${X_AEON_AGENTS_CONFIG:-/etc/x_aeon_agents.rb}"

# Extract the GitHub issue number from the task prompt (generated by
# HarborRunner, e.g. "Implement the Github issue number 42.") and hand the
# work over to `xaa implement-issue`.
instruction="${INSTRUCTION:-}"
if [[ -z "${instruction}" ]]; then
  echo "xaa.sh: INSTRUCTION environment variable is missing or empty" >&2
  exit 1
fi

issue_pattern='[Ii]ssue (number )?#?([0-9]+)'
if [[ "${instruction}" =~ ${issue_pattern} ]]; then
  issue_number="${BASH_REMATCH[2]}"
else
  echo "xaa.sh: no issue number found in INSTRUCTION:" >&2
  echo "${instruction}" >&2
  exit 1
fi

echo "xaa.sh: delegating to xaa for GitHub issue #${issue_number}"

# The container's WORKDIR is /workspace (the cloned sandbox repo),
# so the agent starts directly in the repo; no `cd repo` here.

# Create an isolated worktree for this issue, non-interactively.
# `xaa start-task --branch` skips the STDIN branch-name prompt, creates
# the branch (if needed), sets up the git worktree under .worktrees/, and
# pushes the branch upstream.
branch="issue-${issue_number}"
xaa start-task --branch "${branch}" --no-interactive

# From here on, work inside the worktree so the main checkout stays clean.
# This mirrors TaskStarterAgent's mapping: `.worktrees/<branch with / -> _>`.
worktree=".worktrees/${branch//\//_}"
cd "${worktree}"

# xaa's session state lives under /logs/agent/xaa (see
# x_aeon_agents_config.rb data_dir). That path is a Harbor bind mount
# live on the host at <trial>/agent/xaa/ (next to agent-output.log), so
# it is already visible for debugging -- no tarball step, and nothing to
# clean up here. It is outside /workspace (never pollutes the repo
# artifact) and outside /logs/artifacts (which Harbor re-uploads into the
# verifier), so its deep sessions/... tree is never cp'd or tar'd.

# Run the implementation as the final command. `exec` replaces this shell,
# so xaa's exit code is the script's exit code directly -- no if/else or
# `exit $?` bookkeeping needed (and `set -e` stays happy).
exec xaa implement-issue "${issue_number}" --pr-base main --no-interactive
